import os
from pathlib import Path
import pandas as pd
import numpy as np

root = Path(__file__).resolve().parents[1] / "output" / "bilstm"
out_md = root / "ai_models" / "evaluation_report.md"
out_csv = root / "ai_models" / "evaluation_metrics_test.csv"
out_md.parent.mkdir(parents=True, exist_ok=True)

def pick_exp(top: Path):
    subs = [d for d in top.iterdir() if d.is_dir()]
    if not subs:
        return None
    if len(subs) == 1:
        return subs[0]
    o = [d for d in subs if d.name.startswith('O')]
    if o:
        o.sort(key=lambda x: x.stat().st_mtime, reverse=True)
        return o[0]
    subs.sort(key=lambda x: x.stat().st_mtime, reverse=True)
    return subs[0]

def f1_recall(y_true, y_pred, pos=4):
    y_true = np.asarray(y_true)
    y_pred = np.asarray(y_pred)
    tp = int(((y_true==pos)&(y_pred==pos)).sum())
    fn = int(((y_true==pos)&(y_pred!=pos)).sum())
    fp = int(((y_true!=pos)&(y_pred==pos)).sum())
    recall = tp/(tp+fn) if (tp+fn)>0 else 0.0
    precision = tp/(tp+fp) if (tp+fp)>0 else 0.0
    f1 = (2*precision*recall/(precision+recall)) if (precision+recall)>0 else 0.0
    return recall, f1

rows=[]
for top in sorted([d for d in root.iterdir() if d.is_dir() and d.name!='ai_models'], key=lambda p:p.name):
    exp = pick_exp(top)
    if exp is None:
        continue
    csv_path = exp / 'csv' / 'testset_total_flag.csv'
    if not csv_path.exists():
        rows.append({"folder":top.name,"experiment":exp.name,"status":"missing_testset_total_flag"})
        continue

    try:
        df = pd.read_csv(csv_path, encoding='cp949')
    except Exception:
        df = pd.read_csv(csv_path, encoding='utf-8-sig')

    cols = list(df.columns)
    required = ['flag_2qc_bin','flag_1qc_bin','flag_ai_pot']
    if any(c not in cols for c in required):
        rows.append({"folder":top.name,"experiment":exp.name,"status":"missing_required_cols"})
        continue

    value_candidates = [c for c in cols if c not in ['날짜','date','flag_2qc_bin','flag_1qc_bin','flag_ai_percentile','flag_ai_pot']]
    value_col = value_candidates[0] if value_candidates else None

    use = df.copy()
    if value_col is not None:
        use = use[use[value_col].notna()]

    for c in required:
        use = use[use[c].notna()]

    if len(use)==0:
        rows.append({"folder":top.name,"experiment":exp.name,"status":"no_valid_rows_after_filter","value_col":value_col,"n_total":len(df),"n_used":0})
        continue

    y_true = use['flag_2qc_bin'].astype(int).to_numpy()
    y_1qc = use['flag_1qc_bin'].astype(int).to_numpy()
    y_ai = use['flag_ai_pot'].astype(int).to_numpy()
    y_or = np.where((y_1qc==4)|(y_ai==4),4,1)

    r1,f1_1 = f1_recall(y_true,y_1qc)
    r2,f1_2 = f1_recall(y_true,y_ai)
    r3,f1_3 = f1_recall(y_true,y_or)

    better = (r2>r1) and (f1_2>f1_1)
    fig_pot = exp / 'fig_pot'
    rows.append({
        "folder":top.name,
        "experiment":exp.name,
        "status":"ok",
        "value_col":value_col,
        "n_total":int(len(df)),
        "n_used":int(len(use)),
        "n_excluded":int(len(df)-len(use)),
        "recall_1qc":round(r1,4),
        "f1_1qc":round(f1_1,4),
        "recall_ai_pot":round(r2,4),
        "f1_ai_pot":round(f1_2,4),
        "recall_or":round(r3,4),
        "f1_or":round(f1_3,4),
        "ai_better_than_1qc":bool(better),
        "fig_pot_path":str(fig_pot)
    })

res = pd.DataFrame(rows)
res.to_csv(out_csv, index=False, encoding='utf-8-sig')

ok = res[res['status']=='ok'].copy()
num_ok = len(ok)
num_better = int(ok['ai_better_than_1qc'].sum()) if num_ok else 0

lines=[]
lines.append('# BiLSTM AI QC Evaluation (Test Set)')
lines.append('')
lines.append('- Scope: 36 experiment folders under `output/bilstm` (real folder rule: pick `O*` when multiple).')
lines.append('- Metric dataset: `testset_total_flag.csv` from each selected experiment.')
lines.append('- Filter rule applied: exclude rows with missing original value and rows with missing labels/predictions.')
lines.append('- Metrics: recall, f1 for `1QC`, `AI POT`, `1QC+AI(POT)`.')
lines.append('')
lines.append(f'- Evaluated folders: **{num_ok}**')
lines.append(f'- AI POT better than 1QC (both recall and f1): **{num_better}/{num_ok}**')
lines.append('')
lines.append('## Summary Table')
lines.append('')
if num_ok:
    show_cols=['folder','n_total','n_used','n_excluded','recall_1qc','f1_1qc','recall_ai_pot','f1_ai_pot','recall_or','f1_or','ai_better_than_1qc']
    lines.append(ok[show_cols].to_string(index=False))
else:
    lines.append('No valid evaluation rows.')

lines.append('')
lines.append('## Qualitative Check (POT plot)')
lines.append('')
lines.append('- Use each experiment\'s `fig_pot` folder generated by `plot_all_features_anomaly_with_flags`.')
if num_ok:
    lines.append('')
    for _,r in ok.iterrows():
        lines.append(f"- `{r['folder']}` -> `{r['fig_pot_path']}`")

lines.append('')
lines.append('## Notes')
lines.append('')
lines.append('- This report is computed from existing test-set experiment outputs.')
lines.append('- Train-set metrics and SMB3/SMB4 recent-1year pseudo-test require additional model inference run.')

out_md.write_text('\n'.join(lines), encoding='utf-8')
print(out_md)
print(out_csv)
print({'ok':int(num_ok),'better':int(num_better)})
